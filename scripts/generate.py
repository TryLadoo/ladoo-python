"""Generate the SDK's types and resource classes from the OpenAPI snapshot.

    uv run python scripts/generate.py          # write the generated files
    uv run python scripts/generate.py --check  # fail if they're out of date

Reads ``openapi/openapi.json`` and ``scripts/endpoints.py``. Writes:

- ``src/ladoo/types/_generated.py``: a TypedDict for every schema in the
  document, plus the query and body parameters of each endpoint.
- ``src/ladoo/resources/*.py``: sync and async resource classes, one module per
  top-level namespace.

Only the standard library is used, so it runs anywhere.
"""

from __future__ import annotations

import json
import keyword
import re
import subprocess
import sys
import textwrap
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(Path(__file__).resolve().parent))

from endpoints import ENDPOINTS, Endpoint  # noqa: E402

SPEC_PATH = ROOT / "openapi" / "openapi.json"
TYPES_PATH = ROOT / "src" / "ladoo" / "types" / "_generated.py"
RESOURCES_DIR = ROOT / "src" / "ladoo" / "resources"

HEADER = """# This file is generated by scripts/generate.py from openapi/openapi.json.
# Don't edit it by hand: change the generator or the snapshot and run
# `uv run python scripts/generate.py`.
"""

Schema = dict[str, Any]


def pascal(name: str) -> str:
    parts = re.split(r"[^0-9a-zA-Z]+", name)
    out = "".join(p[:1].upper() + p[1:] for p in parts if p)
    if out and out[0].isdigit():
        out = "_" + out
    return out


def literal(value: object) -> str:
    """A Python literal: JSON's ``true`` is ``True``."""
    return repr(value) if isinstance(value, bool) else json.dumps(value)


def py_name(name: str) -> str:
    """A Python identifier for an API field name (``from`` becomes ``from_``)."""
    return name + "_" if keyword.iskeyword(name) else name


def docstring(text: str | None, indent: str) -> list[str]:
    if not text:
        return []
    text = text.strip().replace("\\", "\\\\").replace('"""', '\\"\\"\\"')
    paragraphs = [p.strip() for p in re.split(r"\n\s*\n", text) if p.strip()]
    lines: list[str] = []
    for i, para in enumerate(paragraphs):
        if i:
            lines.append("")
        lines.extend(textwrap.wrap(" ".join(para.split()), width=88 - len(indent)) or [""])
    if len(lines) == 1 and len(lines[0]) + len(indent) + 6 <= 88 and not lines[0].endswith('"'):
        return [f'{indent}"""{lines[0]}"""']
    out = [f'{indent}"""{lines[0]}']
    out += [f"{indent}{line}" if line else "" for line in lines[1:]]
    out.append(f'{indent}"""')
    return out


class TypeGen:
    """Turns JSON Schemas into Python type expressions and TypedDict classes."""

    def __init__(self, spec: Schema) -> None:
        self.spec = spec
        self.schemas: dict[str, Schema] = spec["components"]["schemas"]
        self.blocks: dict[str, list[str]] = {}  # name -> source lines
        self.aliases: dict[str, str] = {}  # name -> type expression
        self.order: list[str] = []
        self.taken: set[str] = set(self.schemas)

    # Names ------------------------------------------------------------

    def fresh(self, name: str) -> str:
        if name not in self.taken:
            self.taken.add(name)
            return name
        i = 2
        while f"{name}{i}" in self.taken:
            i += 1
        self.taken.add(f"{name}{i}")
        return f"{name}{i}"

    # Schemas ----------------------------------------------------------

    def resolve(self, s: Schema) -> Schema:
        while "$ref" in s:
            s = self.schemas[s["$ref"].split("/")[-1]]
        return s

    def merged(self, s: Schema) -> Schema:
        """Flatten ``allOf`` into one object schema."""
        if "allOf" not in s:
            return s
        props: dict[str, Schema] = {}
        required: list[str] = []
        types: set[str] = set()
        for part in s["allOf"]:
            part = self.merged(self.resolve(part))
            props.update(part.get("properties", {}))
            required += [r for r in part.get("required", []) if r not in required]
            t = part.get("type")
            if isinstance(t, list):
                types.update(t)
        out: Schema = {k: v for k, v in s.items() if k != "allOf"}
        out.update(type="object", properties={**props, **s.get("properties", {})}, required=required)
        if "null" in types:
            out["type"] = ["object", "null"]
        return out

    def expr(self, s: Schema, hint: str, *, files: bool = False) -> str:
        """A type expression for schema ``s``; inline objects become TypedDicts named ``hint``."""
        if "$ref" in s:
            name = s["$ref"].split("/")[-1]
            target = self.merged(self.schemas[name])
            nullable = isinstance(target.get("type"), list) and "null" in target["type"]
            # Aliases carry their own `| None`; TypedDict classes don't.
            return f"{name} | None" if nullable and target.get("properties") else name
        if "allOf" in s:
            if len(s["allOf"]) == 1 and not s.get("properties"):
                return self.expr(s["allOf"][0], hint)
            s = self.merged(s)
        if "oneOf" in s or "anyOf" in s:
            variants = s.get("oneOf") or s.get("anyOf")
            exprs: list[str] = []
            for i, v in enumerate(variants):
                e = self.expr(v, hint + self.variant_suffix(v, i))
                if e not in exprs:
                    exprs.append(e)
            return " | ".join(exprs)

        t = s.get("type")
        types = t if isinstance(t, list) else [t] if t else []
        nullable = "null" in types
        base = [x for x in types if x != "null"]
        suffix = " | None" if nullable else ""

        if "enum" in s:
            values = [v for v in s["enum"] if v is not None]
            if None in s["enum"]:
                suffix = " | None"
            if not values:
                return "None"
            return "Literal[" + ", ".join(literal(v) for v in values) + "]" + suffix
        if "const" in s:
            return f"Literal[{literal(s['const'])}]{suffix}"
        if len(base) > 1:
            return " | ".join(self.expr({**s, "type": b}, hint) for b in base) + suffix
        kind = base[0] if base else ("object" if "properties" in s else None)
        if kind == "string":
            if files and s.get("format") == "binary":
                return "FileTypes" + suffix
            return "str" + suffix
        if kind == "integer":
            return "int" + suffix
        if kind == "number":
            return "float" + suffix
        if kind == "boolean":
            return "bool" + suffix
        if kind == "array":
            if "prefixItems" in s:
                items = [self.expr(x, f"{hint}Item") for x in s["prefixItems"]]
                return f"Tuple[{', '.join(items)}]{suffix}"
            return f"List[{self.expr(s.get('items', {}), hint + 'Item')}]{suffix}"
        if kind == "object":
            if s.get("properties"):
                name = self.fresh(hint)
                self.typed_dict(name, s)
                return name + suffix
            extra = s.get("additionalProperties")
            if isinstance(extra, dict) and extra:
                return f"Dict[str, {self.expr(extra, hint + 'Value')}]{suffix}"
            return "Dict[str, Any]" + suffix
        return "Any"

    def variant_suffix(self, v: Schema, i: int) -> str:
        v = self.resolve(v)
        for prop in v.get("properties", {}).values():
            enum = prop.get("enum")
            if isinstance(enum, list) and len(enum) == 1 and isinstance(enum[0], str):
                return pascal(enum[0])
        return f"Variant{i + 1}"

    def typed_dict(self, name: str, s: Schema, *, total_optional: bool = False, files: bool = False) -> None:
        s = self.merged(self.resolve(s)) if "$ref" in s else self.merged(s)
        required = set() if total_optional else set(s.get("required", []))
        self.order.append(name)
        self.blocks[name] = []  # reserve the slot before recursing
        fields: list[tuple[str, str, str | None]] = []
        for key, prop in s.get("properties", {}).items():
            annotation = self.expr(prop, name + pascal(key), files=files)
            if key not in required:
                annotation = f"NotRequired[{annotation}]"
            fields.append((key, annotation, prop.get("description")))

        lines: list[str] = []
        if all(k.isidentifier() and not keyword.iskeyword(k) for k, _, _ in fields):
            lines.append(f"class {name}(TypedDict):")
            body = docstring(s.get("description"), "    ")
            for key, annotation, desc in fields:
                if body:
                    body.append("")
                body.append(f"    {key}: {annotation}")
                body += docstring(desc, "    ")
            lines += body or ["    pass"]
        else:
            # Field names Python can't spell as attributes need the functional form.
            items = ", ".join(f'"{k}": "{a}"' for k, a, _ in fields)
            lines.append(f"{name} = TypedDict({name!r}, {{{items}}})")
            lines += docstring(s.get("description"), "")
        self.blocks[name] = lines

    def component(self, name: str) -> None:
        s = self.schemas[name]
        merged = self.merged(s)
        is_object = merged.get("type") == "object" or (
            isinstance(merged.get("type"), list) and "object" in merged["type"]
        )
        if is_object and merged.get("properties"):
            self.typed_dict(name, merged)
        else:
            self.taken.discard(name)
            expr = self.expr(s, name + "Value")
            self.aliases[name] = expr
            self.order.append(name)
            self.blocks[name] = [f'{name}: TypeAlias = "{expr}"', *docstring(s.get("description"), "")]

    def params_dict(self, name: str, params: list[Schema]) -> None:
        """A TypedDict of query parameters; Python keywords get a trailing underscore."""
        self.taken.add(name)
        self.order.append(name)
        self.blocks[name] = []
        lines = [f"class {name}(TypedDict, total=False):"]
        body: list[str] = []
        for p in params:
            schema = p.get("schema", {})
            annotation = self.expr(schema, name + pascal(p["name"]))
            if schema.get("format") == "date-time":
                annotation = annotation.replace("str", "str | datetime", 1)
            if p.get("required"):
                annotation = f"Required[{annotation}]"
            if body:
                body.append("")
            body.append(f"    {py_name(p['name'])}: {annotation}")
            body += docstring(p.get("description") or schema.get("description"), "    ")
        self.blocks[name] = lines + (body or ["    pass"])

    def render(self) -> str:
        out = [
            HEADER,
            "from __future__ import annotations",
            "",
            "from datetime import datetime",
            "from typing import IO, Any, Dict, List, Tuple, Union",
            "",
            "from typing_extensions import Literal, NotRequired, Required, TypeAlias, TypedDict",
            "",
            "__all__ = [",
            *[f'    "{n}",' for n in sorted(self.order)],
            '    "FileTypes",',
            "]",
            "",
            'FileTypes: TypeAlias = "Union[bytes, IO[bytes], Tuple[str, Union[bytes, IO[bytes]]], '
            'Tuple[str, Union[bytes, IO[bytes]], str]]"',
            '"""A file to upload: bytes, a binary file object, or a ``(filename, content[, content_type])`` tuple."""',
            "",
        ]
        for name in self.order:
            out += ["", *self.blocks[name], ""]
        return "\n".join(out) + "\n"


# Resources ------------------------------------------------------------


class Op:
    def __init__(self, gen: TypeGen, ep: Endpoint) -> None:
        self.ep = ep
        try:
            self.raw: Schema = gen.spec["paths"][ep.path][ep.method.lower()]
        except KeyError:
            raise SystemExit(f"{ep.method} {ep.path} is not in the OpenAPI document") from None
        path_params = [p["name"] for p in self.raw.get("parameters", []) if p["in"] == "path"]
        template_params = re.findall(r"{([^}]+)}", ep.path)
        if len(ep.args) != len(template_params) or set(path_params) != set(template_params):
            raise SystemExit(f"{ep.path}: args {ep.args} don't match path parameters {template_params}")
        self.base = pascal(ep.ns.replace(".", "_")) + pascal(ep.name)
        self.summary = self.raw.get("summary")
        self.description = self.raw.get("description")

        query = [p for p in self.raw.get("parameters", []) if p["in"] == "query"]
        self.paginated = False
        self.query_type: str | None = None
        if query:
            names = {p["name"] for p in query}
            self.query_type = gen.fresh(self.base + "Params")
            gen.params_dict(self.query_type, [p for p in query if p["name"] != "cursor"])
            self.paginated = "cursor" in names

        # Request body
        self.body_type: str | None = None
        self.body_kwargs = False
        self.file_keys: list[str] = []
        content = self.raw.get("requestBody", {}).get("content", {})
        if content:
            ((ctype, media),) = content.items()
            schema = media.get("schema", {})
            target = gen.merged(gen.resolve(schema))
            if ctype == "multipart/form-data":
                self.body_type = gen.fresh(self.base + "Params")
                gen.typed_dict(self.body_type, target, files=True)
                self.file_keys = [k for k, v in target.get("properties", {}).items() if v.get("format") == "binary"]
                self.body_kwargs = True
            elif "$ref" in schema:
                self.body_type = schema["$ref"].split("/")[-1]
                self.body_kwargs = bool(target.get("properties")) and "oneOf" not in target
            else:
                self.body_type = gen.expr(schema, self.base + "Params")
                self.body_kwargs = bool(target.get("properties")) and "oneOf" not in target
            if self.query_type and self.body_type:
                raise SystemExit(f"{ep.path}: both query and body parameters aren't supported")
            if self.body_kwargs:
                bad = {py_name(k) for k in target.get("properties", {})} & {*ep.args, "request_options"}
                if bad:
                    raise SystemExit(f"{ep.path}: body fields {bad} clash with arguments")

        # Response
        self.returns = "None"
        self.unwrap = False
        self.raw_bytes = False
        for code, resp in sorted(self.raw["responses"].items()):
            if not code.startswith("2"):
                continue
            rcontent = resp.get("content", {})
            if not rcontent:
                break
            ((rtype, rmedia),) = list(rcontent.items())[:1]
            rschema = rmedia.get("schema", {})
            if rtype != "application/json":
                self.returns = "bytes"
                self.raw_bytes = True
                break
            props = rschema.get("properties", {}) if "$ref" not in rschema else {}
            if self.paginated:
                item = gen.expr(props["data"]["items"], self.base + "Item")
                self.returns = item
            elif set(props) == {"data"} and props["data"].get("type") == "array":
                self.returns = gen.expr(props["data"]["items"], self.base + "Item")
                self.unwrap = True
            else:
                self.returns = gen.expr(rschema, self.base + "Response")
            break

    def signature(self, sync: bool) -> tuple[str, str]:
        args = ["self", *[f"{a}: str" for a in self.ep.args]]
        kwargs_type = None
        if self.query_type:
            kwargs_type = self.query_type
        elif self.body_type and self.body_kwargs:
            kwargs_type = self.body_type
        elif self.body_type:
            args.append(f"body: {self.body_type}")
        args += ["*", "request_options: RequestOptions | None = None"]
        if kwargs_type:
            args.append(f"**params: Unpack[{kwargs_type}]")
        if self.paginated:
            ret = f"SyncCursorPage[{self.returns}]" if sync else f"AsyncPaginator[{self.returns}]"
        elif self.unwrap:
            ret = f"List[{self.returns}]"
        else:
            ret = self.returns
        return ", ".join(args), ret

    def render(self, sync: bool) -> list[str]:
        params, ret = self.signature(sync)
        is_async = not sync and not self.paginated
        lines = [f"    {'async ' if is_async else ''}def {self.ep.name}({params}) -> {ret}:"]
        doc = self.summary or ""
        if doc and doc[-1] not in ".?!":
            doc += "."
        if self.description:
            doc += "\n\n" + self.description
        doc += f"\n\n``{self.ep.method} {self.ep.path}``"
        lines += docstring(doc.strip(), "        ")

        path = self.ep.path
        for template_name, arg in zip(re.findall(r"{([^}]+)}", path), self.ep.args):
            path = path.replace("{" + template_name + "}", "{" + f"path_param({arg})" + "}")
        path_expr = f'f"{path}"' if self.ep.args else f'"{path}"'

        if self.paginated:
            lines.append(
                f"        return self._client._request_page({path_expr}, params=params, options=request_options)"
            )
            return lines

        call = [f'"{self.ep.method}"', path_expr]
        if self.query_type:
            call.append("params=params")
        elif self.file_keys:
            call.append(f"multipart=params, file_keys={tuple(self.file_keys)!r}")
        elif self.body_type and self.body_kwargs:
            call.append("json=params")
        elif self.body_type:
            call.append("json=body")
        call.append("options=request_options")
        if self.raw_bytes:
            call.append("raw=True")
        aw = "await " if is_async else ""
        expr = f"{aw}self._client._request({', '.join(call)})"
        if self.returns == "None":
            lines.append(f"        {expr}")
        elif self.unwrap:
            lines.append(f"        response = {expr}")
            lines.append(f'        return cast("{ret}", response["data"])')
        else:
            lines.append(f'        return cast("{ret}", {expr})')
        return lines


def resource_class(ns: str, sync: bool) -> str:
    return ("" if sync else "Async") + pascal(ns.replace(".", "_")) + "Resource"


def render_resources(gen: TypeGen, ops: list[Op]) -> dict[Path, str]:
    """One module per top-level namespace, plus ``__init__.py`` with the client's namespaces."""
    namespaces: dict[str, list[Op]] = {}
    for op in ops:
        parts = op.ep.ns.split(".")
        for i in range(1, len(parts) + 1):
            namespaces.setdefault(".".join(parts[:i]), [])
        namespaces[op.ep.ns].append(op)
    top = [ns for ns in namespaces if "." not in ns]
    files: dict[Path, str] = {}

    for module in top:
        members = {ns: o for ns, o in namespaces.items() if ns == module or ns.startswith(module + ".")}
        module_ops = [op for o in members.values() for op in o]
        used_types = sorted(
            {
                word
                for op in module_ops
                for sync in (True, False)
                for word in re.findall(r"[A-Za-z_][A-Za-z0-9_]*", " ".join(op.signature(sync)))
                if word in gen.blocks
            }
        )
        out = [
            HEADER,
            "# pyright: reportPrivateUsage=false",
            "",
            "from __future__ import annotations",
            "",
            "from functools import cached_property",
            "from typing import TYPE_CHECKING, List, cast",
            "",
            "from typing_extensions import Unpack",
            "",
            "from .._pagination import AsyncPaginator, SyncCursorPage",
            "from .._resource import AsyncAPIResource, SyncAPIResource, path_param",
            "from .._types import RequestOptions",
            "",
            "if TYPE_CHECKING:",
            "    from ..types import (",
            *[f"        {t}," for t in used_types],
            "    )",
            "",
            "__all__ = [",
            *[f'    "{resource_class(ns, s)}",' for ns in members for s in (True, False)],
            "]",
            "",
        ]
        for sync in (True, False):
            for ns, ns_ops in members.items():
                base = "SyncAPIResource" if sync else "AsyncAPIResource"
                label = ns.replace(".", " ").replace("_", " ")
                out += ["", "", f"class {resource_class(ns, sync)}({base}):"]
                out += docstring(f"{'Methods' if sync else 'Async methods'} for {label}.", "    ")
                depth = ns.count(".") + 1
                children = [c for c in members if c.count(".") == depth and c.rsplit(".", 1)[0] == ns]
                for child in children:
                    out += [
                        "",
                        "    @cached_property",
                        f"    def {child.rsplit('.', 1)[1]}(self) -> {resource_class(child, sync)}:",
                        f"        return {resource_class(child, sync)}(self._client)",
                    ]
                for op in ns_ops:
                    out += ["", *op.render(sync)]
        files[RESOURCES_DIR / f"{module}.py"] = "\n".join(out) + "\n"

    out = [
        HEADER,
        "from __future__ import annotations",
        "",
        "from functools import cached_property",
        "from typing import TYPE_CHECKING, cast",
        "",
        *[f"from .{ns} import {resource_class(ns, True)}, {resource_class(ns, False)}" for ns in top],
        "",
        "if TYPE_CHECKING:",
        "    from .._client import AsyncLadoo, Ladoo",
        "",
        "__all__ = [",
        '    "AsyncNamespaces",',
        '    "SyncNamespaces",',
        *[f'    "{resource_class(ns, s)}",' for ns in top for s in (True, False)],
        "]",
    ]
    for sync in (True, False):
        root = "SyncNamespaces" if sync else "AsyncNamespaces"
        client = "Ladoo" if sync else "AsyncLadoo"
        out += ["", "", f"class {root}:"]
        out += docstring(f"The resource namespaces of :class:`ladoo.{client}`.", "    ")
        for ns in top:
            out += [
                "",
                "    @cached_property",
                f"    def {ns}(self) -> {resource_class(ns, sync)}:",
                f'        return {resource_class(ns, sync)}(cast("{client}", self))',
            ]
    files[RESOURCES_DIR / "__init__.py"] = "\n".join(out) + "\n"
    return files


def ruff_format(path: Path) -> None:
    subprocess.run(["ruff", "check", "--quiet", "--fix", "--select", "I,F401", str(path)], check=True, cwd=ROOT)
    subprocess.run(["ruff", "format", "--quiet", str(path)], check=True, cwd=ROOT)


def main() -> int:
    check = "--check" in sys.argv
    spec = json.loads(SPEC_PATH.read_text())
    gen = TypeGen(spec)
    for name in list(gen.schemas):
        gen.component(name)
    ops = [Op(gen, ep) for ep in ENDPOINTS]
    seen: set[tuple[str, str]] = set()
    for op in ops:
        key = (op.ep.ns, op.ep.name)
        if key in seen:
            raise SystemExit(f"duplicate method {key}")
        seen.add(key)

    outputs = {TYPES_PATH: gen.render(), **render_resources(gen, ops)}
    stale: list[Path] = []
    leftovers = [p for p in RESOURCES_DIR.glob("*.py") if p not in outputs and p.read_text().startswith(HEADER)]
    if check:
        stale += leftovers
    else:
        for p in leftovers:
            p.unlink()
    for path, text in outputs.items():
        tmp = path.with_suffix(".tmp.py")
        tmp.write_text(text)
        ruff_format(tmp)
        formatted = tmp.read_text()
        tmp.unlink()
        if check:
            if not path.exists() or path.read_text() != formatted:
                stale.append(path)
        else:
            path.write_text(formatted)
    if stale:
        print("Out of date, run `uv run python scripts/generate.py`:", *stale, sep="\n  ")
        return 1
    print(f"{len(gen.order)} types, {len(ops)} endpoints" + (" (up to date)" if check else ""))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
